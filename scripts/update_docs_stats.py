NOT_A_SHARE = ("index_songs", "outside_denominator")


def coverage_songs(lang: str, coverage: Mapping[str, Any]) -> list[list[str]]:
    t = TEXT[lang]
    denominator = count(coverage, "songs.denominator")
    rows = [(code(key), number(count(coverage, f"songs.{key}")),
             DASH if key in NOT_A_SHARE else percent(count(coverage, f"songs.{key}"), denominator))
            for key in SONG_ROWS]
    return [[t["t_songs"]], table((t["metric"], t["songs"], t["share_head"]), rows, (False, True, True))]


def coverage_lists(lang: str, coverage: Mapping[str, Any]) -> list[list[str]]:
    t = TEXT[lang]
    rows = []
    for section in ("gaps", "mismatches"):
        value = _get(coverage, section)
        if not isinstance(value, dict):
            raise StatsError(f"{section!r} must be an object")
        rows += [(code(f"{section}.{key}"), number(list_length(coverage, f"{section}.{key}"))) for key in value]
    return [[t["t_gaps"]], table((t["metric"], t["entries"]), rows, (False, True))]


def coverage_bytes(lang: str, coverage: Mapping[str, Any]) -> list[list[str]]:
    t = TEXT[lang]
    rows = []
    for group in ("records_by_family", "unique_by_primary_family"):
        rows += [(code(f"{group}.{key}"), size(lang, value))
                 for key, value in counts(coverage, f"bytes.{group}").items()]
    for key in ("unique_total", "by_tier.site", "by_tier.archive", "previews", "catalog_json", "catalog_script",
                "index_html", "coverage_json", "staged_site_estimate", "pages_budget"):
        rows.append((code(key), size(lang, optional_count(coverage, f"bytes.{key}"))))
    staged_verdict(lang, coverage)  # validates within_pages_budget against the two numbers
    rows.append((code("within_pages_budget"), t["yes"] if _get(coverage, "bytes.within_pages_budget") else t["no"]))
    return [[t["t_bytes"]], table((t["metric"], t["bytes_head"]), rows, (False, True))]


def render_coverage(lang: str, coverage: Mapping[str, Any], catalog: Mapping[str, Any]) -> list[str]:
    """docs/coverage: every section of data/coverage.json as tables, in the order of the document."""
    parts: list[list[str]] = []
    parts += coverage_dates(lang, coverage, catalog)
    parts += coverage_sources(lang, coverage)
    parts += coverage_candidates(lang, coverage)
    parts += coverage_files(lang, coverage)
    parts += coverage_songs(lang, coverage)
    parts += coverage_lists(lang, coverage)
    parts += coverage_bytes(lang, coverage)
    return join_parts(parts)


def render_family(lang: str, family: str, coverage: Mapping[str, Any], catalog: Mapping[str, Any]) -> list[str]:
    """docs/sources-<family>: one row per source of the family, with the family's totals above."""
    t = TEXT[lang]
    records = [record for record in coverage_records(coverage) if record["family"] == family]
    keys = list(counts(coverage, "candidates.by_disposition"))
    candidates, _ = _sum_dispositions(records, keys)
    excluded: dict[str, int] = {}
    for record in records:
        for key, value in (record["exclusion_reasons"] or {}).items():
            excluded[key] = excluded.get(key, 0) + value
    intro = t["family_intro"].format(
        family=family, sources=number(len(records)), fetched=snapshots(catalog).get(family) or DASH,
        candidates=number(candidates), records=number(sum(record["asset_records"] for record in records)),
        record_bytes=size(lang, count(coverage, f"bytes.records_by_family.{family}")),
        primary=number(sum(record["primary_unique_files"] for record in records)),
        primary_bytes=size(lang, count(coverage, f"bytes.unique_by_primary_family.{family}")))
    rows = []
    for record in records:
        state = {True: t["complete"], False: t["incomplete"], None: t["no_snapshot"]}[record["discovery_complete"]]
        if record["candidates"] is None:
            values = [DASH] * (len(keys) + 1)
        else:
            values = [number(record["candidates"]), *(number(record["by_disposition"].get(key, 0)) for key in keys)]
        rows.append((code(record["id"]), code(record["status"]), state, *values, number(record["asset_records"]),
                     number(record["primary_unique_files"])))
    header = (t["source"], t["status_head"], t["discovery"], t["candidates"], *map(code, keys), t["records"],
              t["primary"])
    return join_parts([[intro], table(header, rows, (False, False, False, *[True] * (len(header) - 3))),
                       [t["family_reasons"].format(reasons=reasons(lang, excluded))]])


def render(block: str, lang: str, coverage: Mapping[str, Any], catalog: Mapping[str, Any]) -> list[str]:
    if block == "summary":
        return render_summary(lang, coverage, catalog)
    if block == "coverage":
        return render_coverage(lang, coverage, catalog)
    return render_family(lang, block.split(":", 1)[1], coverage, catalog)


