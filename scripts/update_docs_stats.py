def replace_block(text: str, block: Sequence[str], relative: str) -> str:
    """``text`` (LF line ends) with the lines between the marker lines replaced; the marker lines stay as they are."""
    lines = text.split("\n")
    begins = [n for n, line in enumerate(lines) if line.strip() == BEGIN]
    ends = [n for n, line in enumerate(lines) if line.strip() == END]
    if len(begins) != 1 or len(ends) != 1 or begins[0] > ends[0]:
        raise StatsError(f"{relative}: needs exactly one '{BEGIN}' line followed by one '{END}' line")
    if any(marker in line for line in block for marker in ("STATS:BEGIN", "STATS:END")):
        raise StatsError("internal error: a rendered block contains a marker")
    return "\n".join(lines[:begins[0] + 1] + list(block) + lines[ends[0]:])


def document_path(root: Path, relative: str) -> Path:
    path = root / relative
    if path.is_symlink() or not path.is_file():
        raise StatsError(f"{relative}: not a regular file")
    if not path.resolve().is_relative_to(root.resolve()):
        raise StatsError(f"{relative}: outside the root")
    return path


def read_document(path: Path, relative: str) -> tuple[str, str]:
    """(text with LF line ends, the file's line end)."""
    try:
        raw = path.read_bytes().decode("utf-8")
    except UnicodeDecodeError as error:
        raise StatsError(f"{relative}: {error}") from None
    newline = "\r\n" if "\r\n" in raw else "\n"
    return raw.replace("\r\n", "\n"), newline


def write_atomic(path: Path, text: str) -> None:
    mode = stat.S_IMODE(path.stat().st_mode)
    handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(handle, "wb") as stream:
            stream.write(text.encode("utf-8"))
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def plan(root: Path) -> dict[str, tuple[Path, str, str, str]]:
    """relative path -> (path, current text, new text, line end) for every document; nothing is written."""
    coverage, catalog = load_json(root, COVERAGE_JSON), load_json(root, CATALOG_JSON)
    check_inputs(coverage, catalog)
    rendered = {}
    for relative, (block, lang) in DOCUMENTS.items():
        path = document_path(root, relative)
        current, newline = read_document(path, relative)
        rendered[relative] = (path, current, replace_block(current, render(block, lang, coverage, catalog),
                                                           relative), newline)
    return rendered


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                     formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    parser.add_argument("--check", action="store_true", help="compare with the documents without writing")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="repository-shaped tree (default: %(default)s)")
    args = parser.parse_args(argv)
    try:
        documents = plan(args.root)
    except (StatsError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    stale = [relative for relative, (_, current, new, _) in documents.items() if current != new]
    if args.check:
        for relative in stale:
            print(f"Out-of-date statistics block: {relative}", file=sys.stderr)
        return 1 if stale else 0
    try:
        for relative in stale:
            path, _, new, newline = documents[relative]
            write_atomic(path, new.replace("\n", newline))
            print(f"updated {relative}")
    except OSError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
